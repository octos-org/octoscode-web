import { execFileSync } from "node:child_process";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const outputPath = resolve(root, "THIRD_PARTY_LICENSES.md");
const mode = process.argv[2];

if (mode !== "--check" && mode !== "--write") {
  throw new Error(
    "Usage: node scripts/generate-third-party-licenses.mjs --check|--write",
  );
}

const pnpm = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
const inventory = JSON.parse(
  execFileSync(
    pnpm,
    [
      "--filter",
      "@octos-org/octoscode-web",
      "licenses",
      "list",
      "--prod",
      "--json",
    ],
    {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 16 * 1024 * 1024,
    },
  ),
);

const packages = new Map();
for (const [reportedLicense, entries] of Object.entries(inventory)) {
  for (const entry of entries) {
    for (const packagePath of entry.paths) {
      const metadata = JSON.parse(
        await readFile(resolve(packagePath, "package.json"), "utf8"),
      );
      const key = `${metadata.name}@${metadata.version}`;
      const notice = await readPackageNotice(packagePath);
      const record = {
        key,
        license: String(metadata.license ?? reportedLicense),
        homepage: normalizedHomepage(metadata),
        notice,
      };
      const existing = packages.get(key);
      if (existing && JSON.stringify(existing) !== JSON.stringify(record)) {
        throw new Error(`Conflicting license metadata for ${key}`);
      }
      packages.set(key, record);
    }
  }
}

const records = [...packages.values()].sort((left, right) =>
  left.key.localeCompare(right.key),
);
const rendered = render(records);

if (mode === "--write") {
  await writeFile(outputPath, rendered);
  process.stdout.write(
    `Wrote ${records.length} production dependency notices to THIRD_PARTY_LICENSES.md.\n`,
  );
} else {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== rendered) {
    throw new Error(
      "THIRD_PARTY_LICENSES.md is stale; run pnpm licenses:update",
    );
  }
  process.stdout.write(
    `Verified ${records.length} production dependency notices.\n`,
  );
}

async function readPackageNotice(packagePath) {
  const names = (await readdir(packagePath))
    .filter((name) => /^(?:licen[cs]e|copying|notice)(?:$|[._-])/i.test(name))
    .sort((left, right) => left.localeCompare(right));
  const files = [];
  for (const name of names) {
    if (!(await stat(resolve(packagePath, name))).isFile()) continue;
    files.push({
      name,
      text: (await readFile(resolve(packagePath, name), "utf8")).trim(),
    });
  }
  if (!files.length) {
    throw new Error(`No license or notice file found in ${packagePath}`);
  }
  return files
    .map(({ name, text }) => `===== ${name} =====\n${text}`)
    .join("\n\n");
}

function normalizedHomepage(metadata) {
  if (typeof metadata.homepage === "string" && metadata.homepage.trim()) {
    return metadata.homepage.trim();
  }
  const repository =
    typeof metadata.repository === "string"
      ? metadata.repository
      : metadata.repository?.url;
  if (typeof repository !== "string") return null;
  const normalized = repository
    .replace(/^git\+/, "")
    .replace(/^git:\/\/github\.com\//, "https://github.com/")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "");
  return /^[\w.-]+\/[\w.-]+$/.test(normalized)
    ? `https://github.com/${normalized}`
    : normalized;
}

function render(records) {
  const noticeGroups = new Map();
  for (const record of records) {
    const group = noticeGroups.get(record.notice) ?? [];
    group.push(record.key);
    noticeGroups.set(record.notice, group);
  }
  const groups = [...noticeGroups.entries()].sort((left, right) =>
    left[1][0].localeCompare(right[1][0]),
  );

  const lines = [
    "# Production dependency licenses",
    "",
    "<!-- Generated by scripts/generate-third-party-licenses.mjs. Do not edit by hand. -->",
    "",
    "This file records the license material shipped through the production",
    "JavaScript dependency graph. The separately maintained",
    "`THIRD_PARTY_NOTICES.md` records copied or adapted source, including the",
    "DeepSeek Harness UI reference.",
    "",
    "## Inventory",
    "",
  ];

  for (const record of records) {
    const homepage = record.homepage ? ` — ${record.homepage}` : "";
    lines.push(`- \`${record.key}\` — ${record.license}${homepage}`);
  }

  lines.push("", "## License and notice texts", "");
  for (const [index, [notice, keys]] of groups.entries()) {
    lines.push(`### Notice group ${index + 1}`, "", "Applies to:", "");
    for (const key of keys) lines.push(`- \`${key}\``);
    lines.push(
      "",
      ...notice.split("\n").map((line) => (line ? `    ${line}` : "")),
      "",
    );
  }

  return `${lines.join("\n").trimEnd()}\n`;
}
